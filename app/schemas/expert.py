"""
Expert Schemas
Represents security experts and matching results
"""

from pydantic import BaseModel, Field
from typing import Optional
from datetime import datetime


class Expert(BaseModel):
    """Full expert profile from PostgreSQL"""

    id: int
    name: str
    email: str
    phone: Optional[str] = None

    # Professional info
    title: str = Field(description="Professional title")
    bio: str = Field(description="Professional biography")
    years_experience: int = Field(default=0)

    # Skills and certifications
    skills: list[str] = Field(default_factory=list)
    certifications: list[str] = Field(default_factory=list)
    specializations: list[str] = Field(default_factory=list)

    # Service info
    hourly_rate: Optional[float] = None
    currency: str = Field(default="USD")
    availability: bool = Field(default=True)
    response_time: Optional[str] = Field(
        default=None,
        description="Typical response time (e.g., '2 hours', '24 hours')"
    )

    # Location
    location: Optional[str] = None
    timezone: Optional[str] = None
    languages: list[str] = Field(default_factory=lambda: ["English"])

    # Ratings
    rating: float = Field(default=0.0, ge=0.0, le=5.0)
    total_reviews: int = Field(default=0)
    total_cases: int = Field(default=0)

    # Contact
    whatsapp: Optional[str] = None
    linkedin: Optional[str] = None
    website: Optional[str] = None

    # Metadata
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None

    class Config:
        from_attributes = True


class ExpertMatch(BaseModel):
    """Expert match result from Neo4j with scoring"""

    expert_id: int
    match_score: float = Field(ge=0.0, le=1.0)

    # Why this expert matched
    matched_skills: list[str] = Field(default_factory=list)
    matched_certifications: list[str] = Field(default_factory=list)
    match_reasons: list[str] = Field(default_factory=list)

    # Graph traversal info
    path_length: int = Field(
        default=1,
        description="Number of hops in graph to reach this expert"
    )

    # Bonuses applied
    location_bonus: float = Field(default=0.0)
    urgency_bonus: float = Field(default=0.0)
    availability_bonus: float = Field(default=0.0)


class ExpertRecommendation(BaseModel):
    """
    Combined expert profile with match info and AI-generated explanation.
    This is what gets presented to the user.
    """

    expert: Expert
    match: ExpertMatch

    # AI-generated explanation
    explanation: str = Field(
        description="Why this expert is a good fit, generated by Claude"
    )

    # Rank in results
    rank: int = Field(ge=1)

    # Contact options
    contact_options: list[str] = Field(
        default_factory=lambda: ["whatsapp", "email", "schedule_call"]
    )


# Expert fields that must never be returned by public endpoints
PRIVATE_EXPERT_FIELDS = ("email", "phone", "whatsapp")


def public_expert(expert: dict) -> dict:
    """Return an expert profile without private contact details"""
    return {k: v for k, v in expert.items() if k not in PRIVATE_EXPERT_FIELDS}
